#include "vector4.h"

t_v4	v4_div(t_v4 v, double s)
{
	if (fabs(s) < EPS)
		return (v4_crt(0, 0, 0));
	return ((t_v4){
		.x = v.x / s,
		.y = v.y / s,
		.z = v.z / s,
		.w = v.w / s
	});
}
