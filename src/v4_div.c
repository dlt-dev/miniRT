#include "vector4.h"

t_v4	v4_div(t_v4 v, double s)
{
	if (fabs(s) < EPS)
		return ((t_v4){0.0, 0.0, 0.0, 0.0});
	return ((t_v4){v.x / s, v.y / s, v.z / s, v.w / s});
}
