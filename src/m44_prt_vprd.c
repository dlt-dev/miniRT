#include "matrix.h"

void	m44_prt_vprd(const t_m44 *m1, const t_v4 *v1, const t_v4 *v2)
{
	if (!m1 || !v1 || !v2)
		return ;
	printf(
		"╭%8.3f %8.3f %8.3f %8.3f╮   ╭ %8.3f ╮   ╭ %8.3f ╮\n"
		"│%8.3f %8.3f %8.3f %8.3f│ * │ %8.3f │ = │ %8.3f │\n"
		"│%8.3f %8.3f %8.3f %8.3f│   │ %8.3f │   │ %8.3f │\n"
		"╰%8.3f %8.3f %8.3f %8.3f╯   ╰ %8.3f ╯   ╰ %8.3f ╯\n",
		(*m1)[0], (*m1)[1], (*m1)[2], (*m1)[3],
		v1->x, v2->x,
		(*m1)[4], (*m1)[5], (*m1)[6], (*m1)[7],
		v1->y, v2->y,
		(*m1)[8], (*m1)[9], (*m1)[10], (*m1)[11],
		v1->z, v2->z,
		(*m1)[12], (*m1)[13], (*m1)[14], (*m1)[15],
		v1->w, v2->w
		);
}
