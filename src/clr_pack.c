#include "color.h"

inline uint32_t	clr_pack(const t_clr c)
{
	return (
		(uint32_t)(c.t * 255.0 + 0.5) << 24 |
		(uint32_t)(c.r * 255.0 + 0.5) << 16 |
		(uint32_t)(c.g * 255.0 + 0.5) << 8 |
		(uint32_t)(c.b * 255.0 + 0.5)
		);
}
