#include "vector4.h"

t_v4	v4_sub(t_v4 a, t_v4 b)
{
	return ((t_v4){
		.x = a.x - b.x,
		.y = a.y - b.y,
		.z = a.z - b.z,
		.w = a.w - b.w
	});
}
