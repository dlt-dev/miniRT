int	m44_zro(t_m44 *m1)
{
	int	i;

	if (!m1)
		return (-1);
	i = 0;
	while (i < M44_SIZE * M44_SIZE)
	{
		(*m1)[i] = 0.0;
		i++;
	}
	return (0);
}
