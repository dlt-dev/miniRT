#include "transformations.h"

int	m44_trl(double tx, double ty, double tz, t_m44 *res)
{
	if (!res)
		return (-1);
	t_m44 tmp = {
		1.0, 0.0, 0.0, tx,
		0.0, 1.0, 0.0, ty,
		0.0, 0.0, 1.0, tz,
		0.0, 0.0, 0.0, 1.0};
	memcpy(*res, tmp, sizeof(t_m44));
	return (0);
}
