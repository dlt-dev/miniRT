#include "vector4.h"

void	v4_prt(const t_v4 *v)
{
	if (!v)
		return ;
	printf(
		"╭ %8.3f ╮\n"
		"│ %8.3f │\n"
		"│ %8.3f │\n"
		"╰ %8.3f ╯\n",
		v->x, v->y, v->z, v->w
		);
}
