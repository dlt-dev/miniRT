#include "vector4.h"

t_v4	v4_xpr(t_v4 a, t_v4 b)
{
	return ((t_v4){
		.x = a.y * b.z - a.z * b.y,
		.y = a.z * b.x - a.x * b.z,
		.z = a.x * b.y - a.y * b.x,
		.w = 0.0
	});
}
