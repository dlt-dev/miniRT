#include "vector3.h"

t_v3	v3_xpr(t_v3 a, t_v3 b)
{
	return ((t_v3){
		a.y * b.z - a.z * b.y,
		a.z * b.x - a.x * b.z,
		a.x * b.y - a.y * b.x,
		0.0
	});
}
