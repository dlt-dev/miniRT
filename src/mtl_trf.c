#include "material.h"

int	mtl_trf(t_mtl *mtl, t_trf *trf)
{
	if (!mtl || !trf)
		return (-1);
	m44_cpy(&(trf->tm), &(mtl->tm));
	m44_cpy(&(trf->itm), &(mtl->itm));
	return (0);
}
