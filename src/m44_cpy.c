#include "matrix.h"

int	m44_cpy(const t_m44 *m1, t_m44 *res)
{
	int	i;

	if (!res || !m1)
		return (-1);
	i = 0;
	while (i < M44_SIZE * M44_SIZE)
	{
		(*res)[i] = (*m1)[i];
		i++;
	}
	return (0);
}
