#include "color.h"

t_clr	clr_unpack(uint32_t packed)
{
	return ((t_clr)
		{
			((packed >> 24) & 0xFF) / 255.0,
			((packed >> 16) & 0xFF) / 255.0,
			((packed >> 8) & 0xFF) / 255.0,
			(packed & 0xFF) / 255.0,
		});
}
