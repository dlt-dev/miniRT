#include "vector3.h"

t_vect3	vect3_cross(t_vect3 a, t_vect3 b)
{
	return ((t_vect3){a.y * b.z - a.z * b.y, a.z * b.x - a.x * b.z, a.x * b.y
		- a.y * b.x});
}
