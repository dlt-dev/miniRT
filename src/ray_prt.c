#include "ray.h"

void	ray_prt(const t_ray *ray)
{
	printf(
		"╭ %8.3f ╮    ╭ %8.3f ╮\n"
		"│ %8.3f │ + t│ %8.3f │\n"
		"│ %8.3f │    │ %8.3f │\n"
		"╰ %8.3f ╯    ╰ %8.3f ╯\n",
		ray->o.x, ray->dir.x,
		ray->o.y, ray->dir.y,
		ray->o.z, ray->dir.z,
		ray->o.w, ray->dir.w
		);
}
