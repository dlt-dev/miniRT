#include "matrix.h"

int	m44_vprd(const t_m44 *m1, const t_v4 *v1, t_v4 *res)
{
	if (!m1 || !v1 || !res)
		return (-1);
	res->x = (*m1)[0] * v1->x + (*m1)[1] * v1->y
		+ (*m1)[2] * v1->z + (*m1)[3] * v1->w;
	res->y = (*m1)[4] * v1->x + (*m1)[5] * v1->y
		+ (*m1)[6] * v1->z + (*m1)[7] * v1->w;
	res->z = (*m1)[8] * v1->x + (*m1)[9] * v1->y
		+ (*m1)[10] * v1->z + (*m1)[11] * v1->w;
	res->w = (*m1)[12] * v1->x + (*m1)[13] * v1->y
		+ (*m1)[14] * v1->z + (*m1)[15] * v1->w;
	return (0);
}
