#include "matrix.h"

int	m44_idm(t_m44 *res)
{
	int	i;

	if (!res)
		return (-1);
	if (m44_zro(res) != 0)
		return (-1);
	i = 0;
	while (i < M44_SIZE)
	{
		(*res)[i * M44_SIZE + i] = 1.0;
		i++;
	}
	return (0);
}
