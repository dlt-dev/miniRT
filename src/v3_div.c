#include "v3.h"

t_v3	v3_div(t_v3 v, double s)
{
	if (fabs(s) < EPS)
		return ((t_v3){0.0, 0.0, 0.0});
	return ((t_v3){v.x / s, v.y / s, v.z / s});
}
