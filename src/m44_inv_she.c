#include "matrix.h"

// Given a Shearing Matrix M shaped as :
// 		| 1   a   b   0 |
// 	M =	| c   1   d   0 |
// 		| e   f   1   0 |
// 		| 0   0   0   1 |
// Let D = det(M) = 1 + ade + bcf − ac − be − df
// Then M^-1 is shaped as :
// 				| 1 - d*f	b*f - a		a*d - b    	0 |
// M^-1 = 1/D * | d*e - c	1 - b*e		c*b - d		0 |
//         		| c*f - e	e*a - f		1 - a*c		0 |
//         		| 0         0           0			1 |

static double	she_det(const t_m44 *m1)
{
	return (
		1
		+ (*m1)[1] * (*m1)[6] * (*m1)[8]
		+ (*m1)[2] * (*m1)[4] * (*m1)[9]
		- (*m1)[1] * (*m1)[4]
		- (*m1)[2] * (*m1)[8]
		- (*m1)[6] * (*m1)[9]
	);
}

int	m44_inv_she(const t_m44 *m1, t_m44 *res)
{
	double	det;

	if (!m1 || !res)
		return (-1);
	det = she_det(m1);
	if (deql(det, 0.0))
		return (-1);
	(*res)[0] = (1 - (*m1)[6] * (*m1)[9]) / det;
	(*res)[1] = ((*m1)[2] * (*m1)[9] - (*m1)[1]) / det;
	(*res)[2] = ((*m1)[1] * (*m1)[6] - (*m1)[2]) / det;
	(*res)[3] = 0.0;
	(*res)[4] = ((*m1)[6] * (*m1)[8] - (*m1)[4]) / det;
	(*res)[5] = (1 - (*m1)[2] * (*m1)[8]) / det;
	(*res)[6] = ((*m1)[4] * (*m1)[2] - (*m1)[6]) / det;
	(*res)[7] = 0.0;
	(*res)[8] = ((*m1)[4] * (*m1)[9] - (*m1)[8]) / det;
	(*res)[9] = ((*m1)[8] * (*m1)[1] - (*m1)[9]) / det;
	(*res)[10] = (1 - (*m1)[1] * (*m1)[4]) / det;
	(*res)[11] = 0.0;
	(*res)[12] = 0.0;
	(*res)[13] = 0.0;
	(*res)[14] = 0.0;
	(*res)[15] = 1.0;
	return (0);
}
