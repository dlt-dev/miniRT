#include "matrix.h"

void	m44_prt(const t_m44 *m1)
{
	if (!m1)
		return ;
	printf(
		"╭%8.3f %8.3f %8.3f %8.3f╮\n"
		"│%8.3f %8.3f %8.3f %8.3f│\n"
		"│%8.3f %8.3f %8.3f %8.3f│\n"
		"╰%8.3f %8.3f %8.3f %8.3f╯\n",
		(*m1)[0], (*m1)[1], (*m1)[2], (*m1)[3],
		(*m1)[4], (*m1)[5], (*m1)[6], (*m1)[7],
		(*m1)[8], (*m1)[9], (*m1)[10], (*m1)[11],
		(*m1)[12], (*m1)[13], (*m1)[14], (*m1)[15]
		);
}
