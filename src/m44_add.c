#include "matrix.h"

void	m44_add(const t_m44 *m1, const t_m44 *m2, t_m44 *res)
{
	int	i;

	if (!m1 || !m2 || !res)
		return (-1);
	i = 0;
	while (i < M44_SIZE * M44_SIZE)
	{
		(*res)[i] = (*m1)[i] + (*m2)[i];
		i++;
	}
	return (0);
}
